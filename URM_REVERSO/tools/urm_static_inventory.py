#!/usr/bin/env python3
"""Read-only inventory of URM converted .rpy files and Ren'Py 7.4.11 references."""
import ast
import csv
import hashlib
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
URM = ROOT / "URM_REVERSO/01_MATERIAL_URM/2_URM_X52_CONVERTIDO"
SDK = ROOT / "renpy-7.4.11-sdk"
OUT = pathlib.Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT / "urm_inventory_output"
DECL = re.compile(r"^\s*(?:class|def|screen|label|init|transform|default|define)\s+([\w.]+)", re.M)
REF = re.compile(r"\b(?:renpy(?:\.[A-Za-z_]\w*)+|(?:x52URM|URMFiles|VarsStore|Search|Settings|CodeView|Choices|PathDetection|Snapshots|GameSaves)\.[A-Za-z_]\w*)")
IMPORT = re.compile(r"^\s*(?:from\s+[\w.]+\s+import\s+[^#\n]+|import\s+[^#\n]+)", re.M)

def scan(root, kind):
    rows, refs, imports = [], [], []
    for p in sorted(root.rglob("*.rpy" if kind == "urm" else "*.py")):
        if not p.is_file():
            continue
        raw = p.read_bytes()
        txt = raw.decode("utf-8-sig", errors="replace")
        rel = p.relative_to(ROOT).as_posix()
        lines = txt.splitlines()
        for i, line in enumerate(lines, 1):
            match = DECL.match(line)
            if match:
                rows.append({"source":kind,"file":rel,"line":i,"kind":line.lstrip().split()[0],"symbol":match.group(1),"sha256":hashlib.sha256(raw).hexdigest()})
            if kind == "urm":
                for ref in sorted(set(REF.findall(line))):
                    refs.append({"file":rel,"line":i,"reference":ref,"evidence":line.strip()[:240]})
                if IMPORT.match(line):
                    imports.append({"file":rel,"line":i,"statement":line.strip()[:240]})
    return rows, refs, imports

def csv_write(name, rows, fields):
    with (OUT / name).open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)

def main():
    if not URM.is_dir() or not SDK.is_dir():
        raise SystemExit("Required URM converted sources or SDK 7.4.11 not found")
    OUT.mkdir(parents=True, exist_ok=True)
    ur, refs, imports = scan(URM, "urm")
    sdk, _, _ = scan(SDK / "renpy", "sdk")
    csv_write("urm_declarations.csv", ur, ["source","file","line","kind","symbol","sha256"])
    csv_write("sdk_declarations.csv", sdk, ["source","file","line","kind","symbol","sha256"])
    csv_write("urm_references.csv", refs, ["file","line","reference","evidence"])
    csv_write("urm_imports.csv", imports, ["file","line","statement"])
    summary = {"method":"static regex extraction; not semantic validation","urm_declarations":len(ur),"sdk_declarations":len(sdk),"urm_references":len(refs),"urm_imports":len(imports),"urm_root":URM.relative_to(ROOT).as_posix(),"sdk_root":SDK.relative_to(ROOT).as_posix()}
    (OUT / "summary.json").write_text(json.dumps(summary,indent=2,ensure_ascii=False)+"\n",encoding="utf-8")
    (OUT / "README.md").write_text("# URM static inventory\n\nGenerated by a read-only extractor. Matches are **candidates**, not verified call edges or behavioral claims. Review each cited file and line against URM and Ren'Py 7.4.11 before accepting conclusions. No runtime tests were performed.\n",encoding="utf-8")
    print(json.dumps(summary,indent=2))
if __name__ == "__main__":
    main()
